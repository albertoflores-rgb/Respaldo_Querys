


SELECT
T3.ITEM_NBR,
T3.OLD_NBR,
T2.UPC_NBR,
T2.REPL_GROUP_NBR AS CID,
T3.PRIMARY_DESC,
T2.DEPT_NBR,
T3.type_code,
T3.EFFECTIVE_DATE,
T3.COST,
T3.CANCEL_WHEN_OUT_FLAG,
T1.STORE_NBR,
T1.ON_HAND_1_QTY AS OH,
T1.ON_HAND_1_QTY*T3.COST AS OHCOST

FROM
wmt-edw-prod.MX_WM_VM.INFOREM_MANAGED_SKU T1
JOIN
wmt-edw-prod.MX_WM_VM.ITEM T2
ON (T1.ITEM_NBR=T2.ITEM_NBR)
JOIN
wmt-edw-prod.MX_WM_VM.ITEM_DESC T3
ON (T1.ITEM_NBR=T3.ITEM_NBR)


WHERE 


primary_desc like "%19%"

